const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const request = require('supertest');
const app = require('../app');
const Users = require('../models/user.model');
const Notes = require('../models/note.model');
let userId, otherUserId, noteId;
before(async () => {
  const uri = process.env.TEST_MONGO_URI || 'mongodb://127.0.0.1:27017/sticky_notes_assignment_test';
  {
    const name = new URL(uri).pathname.slice(1);
    if (!name.endsWith('_test')) throw new Error('TEST_MONGO_URI database must end in _test; this suite drops that database.');
    await mongoose.connect(uri, { serverSelectionTimeoutMS: 5000 });
  }
  await Users.init();
});
after(async () => { if (mongoose.connection.readyState === 1) await mongoose.connection.dropDatabase(); await mongoose.disconnect(); });
const user = { name: 'Student', email: 'student@example.com', password: 'test-password', Phone: '01012345678', age: 22 };
const url = path => `${path}${path.includes('?') ? '&' : '?'}userId=${userId}`;
test('all assignment operations and negative scenarios', async () => {
  let result = await request(app).post('/users/signup').send({ ...user, email: ' STUDENT@example.com ' }).expect(201);
  userId = result.body.user._id;
  assert.equal(result.body.message, 'User added successfully.');
  assert.equal(result.body.user.Password, undefined);
  const stored = await Users.findById(userId).select('+Password');
  assert.match(stored.Password, /^\$2/);
  await request(app).post('/users/signup').send(user).expect(409);
  for (const age of [17, 61, null, '20']) await request(app).post('/users/signup').send({ ...user, email: 'age@example.com', age }).expect(400);
  await request(app).post('/users/signup').send({}).expect(400);
  await request(app).post('/users/signup').set('Content-Type', 'application/json').send('{invalid').expect(400);
  await request(app).post('/users/signup').send({ ...user, email: 'bad' }).expect(400);
  result = await request(app).post('/users/signup').send({ ...user, email: 'other@example.com', age: undefined }).expect(201);
  otherUserId = result.body.user._id;
  result = await request(app).post('/users/login').send({ email: user.email, password: user.password }).expect(200);
  assert.equal(result.body.userId, userId);
  assert.equal(result.body.user.Password, undefined);
  await request(app).post('/users/login').send({ email: user.email, password: 'wrong' }).expect(401);
  await request(app).get(url('/users')).expect(200);
  await request(app).patch(url(`/users/${userId}`)).send({ name: 'Updated Student' }).expect(200);
  await request(app).patch(url(`/users/${userId}`)).send({ Password: 'forbidden' }).expect(400);
  await request(app).patch(url(`/users/${userId}`)).send({ email: 'other@example.com' }).expect(409);
  await request(app).patch(url(`/users/${otherUserId}`)).send({ name: 'Mismatch' }).expect(400);
  await request(app).get('/users?userId=bad').expect(400);
  await request(app).get('/users?userId=000000000000000000000000').expect(404);
  for (const title of ['FIRST NOTE', 'A123!']) await request(app).post(url('/notes')).send({ title, content: 'Test' }).expect(400);
  await request(app).post(url('/notes')).send({ title: 'Valid' }).expect(400);
  for (const title of ['123!', 'مرحبا']) { const note = new Notes({ title, content: 'Text', userId }); await note.validate(); }
  result = await request(app).post(url('/notes')).send({ title: 'First Note', content: 'Workout Plan' }).expect(201);
  noteId = result.body.note._id;
  assert.ok(result.body.note.createdAt && result.body.note.updatedAt);
  await request(app).get(url(`/notes/${noteId}`)).expect(200);
  for (const method of ['get', 'patch', 'delete']) await request(app)[method](`/notes/${noteId}?userId=${otherUserId}`).send({ title: 'Forbidden' }).expect(403);
  await request(app).put(`/notes/replace/${noteId}?userId=${otherUserId}`).send({ title: 'Forbidden', content: 'Test' }).expect(403);
  await request(app).patch(url(`/notes/${noteId}`)).send({ title: 'UPPERCASE' }).expect(400);
  result = await request(app).patch(url(`/notes/${noteId}`)).send({ title: 'Updated Title' }).expect(200);
  assert.equal(result.body.content, 'Workout Plan');
  await request(app).put(url(`/notes/replace/${noteId}`)).send({ title: 'Missing content' }).expect(400);
  await request(app).put(url(`/notes/replace/${noteId}`)).send({ title: 'UPPER', content: 'Test' }).expect(400);
  await request(app).patch(url(`/notes/${noteId}`)).send({ userId: otherUserId }).expect(400);
  result = await request(app).put(url(`/notes/replace/${noteId}`)).send({ title: 'Replacement', content: 'Workout Plan' }).expect(200);
  assert.equal(result.body.userId, userId);
  await request(app).patch(url('/notes/all')).send({ title: 'UPPER' }).expect(400);
  await request(app).patch(url('/notes/all')).send({ title: 'Code Review Notes' }).expect(200);
  result = await request(app).get(url('/notes/paginate-sort?page=1&limit=3')).expect(200);
  assert.equal(result.body.total, 1); assert.equal(result.body.notes.length, 1);
  for (const page of ['0', '-1', 'abc', '1.5', '']) await request(app).get(url(`/notes/paginate-sort?page=${page}`)).expect(400);
  await request(app).get(url('/notes/paginate-sort?limit=101')).expect(400);
  result = await request(app).get(url('/notes/note-by-content?content=Workout%20Plan')).expect(200);
  assert.equal(result.body._id, noteId);
  await request(app).get(url('/notes/note-by-content?content=Workout')).expect(404);
  result = await request(app).get(url('/notes/note-with-user')).expect(200);
  assert.deepEqual(Object.keys(result.body[0]).sort(), ['_id', 'createdAt', 'title', 'userId']);
  assert.deepEqual(result.body[0].userId, { email: user.email });
  result = await request(app).get(url('/notes/aggregate?title=Code%20Review%20Notes')).expect(200);
  assert.deepEqual(result.body[0].user, { name: 'Updated Student', email: user.email });
  await request(app).get(url('/notes/000000000000000000000000')).expect(404);
  await request(app).get(url('/notes/not-an-id')).expect(400);
  await request(app).delete(url(`/notes/${noteId}`)).expect(200);
  await request(app).patch(url('/notes/all')).send({ title: 'No notes' }).expect(404);
  await request(app).post(url('/notes')).send({ title: 'Another', content: 'Text' }).expect(201);
  await request(app).delete(url('/notes')).expect(200);
  assert.equal(await Notes.countDocuments({ userId }), 0);
  await request(app).post(url('/notes')).send({ title: 'Cascade', content: 'Text' }).expect(201);
  await request(app).delete(url('/users')).expect(200);
  assert.equal(await Notes.countDocuments({ userId }), 0);
  await request(app).delete(url('/users')).expect(404);
  await request(app).post(url('/notes')).send({ title: 'Orphan', content: 'Text' }).expect(404);
  await request(app).delete(`/users?userId=${otherUserId}`).expect(200);
});
test('pagination sorts newest first and excludes other users', async () => {
  const first = await Users.create({ name: 'One', email: 'page-one@example.com', Password: 'test-only-hash', Phone: '010' });
  const second = await Users.create({ name: 'Two', email: 'page-two@example.com', Password: 'test-only-hash', Phone: '010' });
  for (let i = 0; i < 4; i++) await Notes.create({ title: `Note ${i}`, content: 'Content', userId: first._id, createdAt: new Date(2025, 0, i + 1) });
  await Notes.create({ title: 'Other user', content: 'Private', userId: second._id });
  const result = await request(app).get(`/notes/paginate-sort?userId=${first.id}&page=2&limit=2`).expect(200);
  assert.equal(result.body.total, 4); assert.equal(result.body.totalPages, 2);
  assert.deepEqual(result.body.notes.map(note => note.title), ['Note 1', 'Note 0']);
});
