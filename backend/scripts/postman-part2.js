// Extend A-I without changing existing requests. J-M use their own generated identity.
module.exports = function ({ group, add, current, capture }) {
  const user = { name: 'Part two student', email: '{{part2Email}}', password: 'Course-password-123', Phone: '+201012345678', username: '{{part2Username}}' };
  const login = { email: '{{part2Email}}', password: 'Course-password-123' };
  const save = [capture('data.accessToken', 'part2Token'), capture('data.refreshToken', 'part2Refresh')];
  const manual = (variable, instructions) => {
    const item = current().item.at(-1);
    item.request.description = instructions;
    item.event.unshift({ listen: 'prerequest', script: { type: 'text/javascript', exec: [`if (!pm.environment.get('${variable}')) pm.execution.skipRequest();`] } });
  };
  group('J - Google Login, Regex and Redis');
  add('Part2RegisterUser', 'POST', '/auth/signup', user, 201, null, save);
  current().item.at(-1).event.unshift({ listen: 'prerequest', script: { type: 'text/javascript', exec: ["const tag = Date.now().toString(36); pm.environment.set('part2Email', 'part2-' + tag + '@example.com'); pm.environment.set('part2Username', 'part2_' + tag);"] } });
  for (const [name, patch] of [['SignupInvalidUsername', { username: 'admin' }], ['SignupInvalidPhone', { Phone: '123' }], ['SignupInvalidPassword', { password: 'short' }], ['SignupInvalidEmail', { email: 'bad' }]]) add(name, 'POST', '/auth/signup', { ...user, ...patch }, 400);
  add('SignupDuplicateUsername', 'POST', '/auth/signup', { ...user, email: 'duplicate-{{part2Email}}' }, 409);
  add('Part2GoogleValidToken', 'POST', '/auth/google', { idToken: '{{googleIdToken}}' }, 200);
  manual('googleIdToken', 'Manual: configure GOOGLE_CLIENT_ID and supply a real Google ID token. Live provider verification remains external.');
  add('Part2GoogleInvalidToken', 'POST', '/auth/google', { idToken: 'malformed' }, 401);
  manual('googleConfigured', 'Set googleConfigured only when GOOGLE_CLIENT_ID is configured; otherwise endpoint returns 503.');
  add('GoogleWrongAudience', 'POST', '/auth/google', { idToken: '{{googleWrongAudienceToken}}' }, 401);
  manual('googleWrongAudienceToken', 'Manual real token issued to a different audience.');
  group('K - Redis Sessions, Logout and Mail');
  add('LoginDeviceOne', 'POST', '/auth/login', login, 200, null, save);
  add('LoginDeviceTwo', 'POST', '/auth/login', login, 200, null, [capture('data.accessToken', 'deviceTwoToken'), capture('data.refreshToken', 'deviceTwoRefresh')]);
  add('GetProfileDeviceOne', 'GET', '/auth/profile', undefined, 200, 'part2Token');
  add('GetProfileDeviceTwo', 'GET', '/auth/profile', undefined, 200, 'deviceTwoToken');
  add('LogoutCurrentDevice', 'POST', '/auth/logout', {}, 200, 'part2Token');
  add('VerifyDeviceOneRevoked', 'GET', '/auth/profile', undefined, 401, 'part2Token');
  add('VerifyDeviceTwoStillActive', 'GET', '/auth/profile', undefined, 200, 'deviceTwoToken');
  add('LogoutAllDevices', 'POST', '/auth/logout-all', {}, 200, 'deviceTwoToken');
  add('VerifyAllSessionsRevoked', 'GET', '/auth/profile', undefined, 401, 'deviceTwoToken');
  add('InvalidRefreshAfterLogout', 'POST', '/auth/refresh', { refreshToken: '{{deviceTwoRefresh}}' }, 401);
  group('L - Email Verification, OTP and Recovery');
  add('LoginForEmailVerification', 'POST', '/auth/login', login, 200, null, save);
  add('RequestEmailVerification', 'POST', '/auth/email/request', {}, 200, 'part2Token');
  current().item.at(-1).request.description = 'Sends directly to the configured backend. Read the OTP in Mailpit, never an API response. Only the unattended test runner explicitly opts out with skipExternalMail=true.';
  current().item.at(-1).event.unshift({ listen: 'prerequest', script: { type: 'text/javascript', exec: ["if (pm.environment.get('skipExternalMail') === 'true') pm.execution.skipRequest();"] } });
  add('ResendBeforeCooldown', 'POST', '/auth/email/request', {}, 429, 'part2Token');
  current().item.at(-1).request.description = 'Run immediately after RequestEmailVerification. Only the unattended test runner explicitly opts out with skipExternalMail=true.';
  current().item.at(-1).event.unshift({ listen: 'prerequest', script: { type: 'text/javascript', exec: ["if (pm.environment.get('skipExternalMail') === 'true') pm.execution.skipRequest();"] } });
  add('ConfirmEmailWrongOTP', 'POST', '/auth/email/confirm', { code: '000000' }, 400, 'part2Token');
  add('ConfirmEmailValidOTP', 'POST', '/auth/email/confirm', { code: '{{emailOtp}}' }, 200, 'part2Token');
  manual('emailOtp', 'Copy the current confirmation code from the local SMTP inbox.');
  add('ConfirmEmailReusedOTP', 'POST', '/auth/email/confirm', { code: '{{emailOtp}}' }, 400, 'part2Token');
  manual('emailOtp', 'Run after successful confirmation using the same code.');
  add('VerifyEmailStatus', 'GET', '/auth/profile', undefined, 200, 'part2Token');
  add('RequestForgotPassword', 'POST', '/auth/password/forgot', { email: '{{part2Email}}' });
  add('RequestForgotPasswordUnknownEmail', 'POST', '/auth/password/forgot', { email: 'unknown-{{part2Email}}' });
  group('M - Password Reset and Multer Uploads');
  add('VerifyPasswordResetWrongOTP', 'POST', '/auth/password/verify', { email: '{{part2Email}}', code: '000000' }, 400);
  add('VerifyPasswordResetOTP', 'POST', '/auth/password/verify', { email: '{{part2Email}}', code: '{{recoveryOtp}}' }, 200, null, [capture('data.resetToken', 'resetToken')]);
  manual('recoveryOtp', 'Copy recovery OTP from Mailpit after RequestForgotPassword.');
  add('ResetPassword', 'POST', '/auth/password/reset', { email: '{{part2Email}}', resetToken: '{{resetToken}}', password: 'New-course-password-123' });
  manual('resetToken', 'Requires successful recovery verification; credential expires after five minutes.');
  add('RejectReusedResetAuthorization', 'POST', '/auth/password/reset', { email: '{{part2Email}}', resetToken: '{{resetToken}}', password: 'New-course-password-123' }, 400);
  manual('resetToken', 'Run after ResetPassword with same credential.');
  add('RejectOldPassword', 'POST', '/auth/login', login, 401);
  manual('resetToken', 'Run after successful password reset.');
  add('LoginWithNewPassword', 'POST', '/auth/login', { email: '{{part2Email}}', password: 'New-course-password-123' }, 200, null, save);
  manual('resetToken', 'Run after successful password reset.');
  const file = (name, fixture, status, token = 'part2Token') => {
    add(name, 'POST', '/auth/avatar', undefined, status, token, status === 200 ? [capture('data.avatar', 'avatarUrl')] : []);
    current().item.at(-1).request.body = { mode: 'formdata', formdata: [{ key: 'avatar', type: 'file', src: `postman/fixtures/${fixture}` }] };
  };
  file('UploadWithoutToken', 'avatar.png', 401, null);
  file('UploadValidAvatar', 'avatar.png', 200);
  add('GetPublicAvatar', 'GET', '{{avatarUrl}}');
  current().item.at(-1).event = [{ listen: 'test', script: { type: 'text/javascript', exec: ["pm.test('HTTP 200', () => pm.response.to.have.status(200));", "pm.test('WebP content', () => pm.expect(pm.response.headers.get('Content-Type')).to.include('image/webp'));"] } }];
  file('UploadFakeImage', 'fake.png', 415);
  file('UploadWrongFileType', 'unsupported.txt', 415);
  file('UploadOversizedAvatar', 'oversized.png', 413);
  file('ReplaceAvatar', 'avatar.png', 200);
  add('GetProfileAfterResetOrUpload', 'GET', '/auth/profile', undefined, 200, 'part2Token');
  add('CleanupPart2Account', 'DELETE', '/auth/account', undefined, 200, 'part2Token');
};
